import assert from 'node:assert/strict';
import { createCoreBridge } from '../core-bridge.js';

const origin = process.argv[2];
const jobId = process.argv[3];
const instanceId = '11111111-1111-4111-8111-111111111111';
assert.equal(new URL(origin).hostname, '127.0.0.1');
const handler = createCoreBridge({ getProvider: () => ({ baseURL: origin + '/v1' }), resolveCredential: async () => undefined });
const call = (method, payload) => handler(method, payload, undefined, { principal: { kind: 'owner' } });
const value = async (method, payload) => {
  const reply = await call(method, payload);
  assert.equal(reply.ok, true, JSON.stringify(reply));
  return reply.value;
};
const read = (resource, params) => value('core/read', { resource, ...(params ? { params } : {}) });
const inventory = () => read('prefix_cache');
assert.equal((await inventory()).total_blocks, 4);
assert.equal((await call('cache/purge', { scope: 'all' })).error.code, 'tyloinfer/bad-request');
assert.equal((await inventory()).total_blocks, 4);
const preview = await value('cache/text', { namespace: 'a'.repeat(64), block: '1'.repeat(64), offset: 4, limit: 3 });
assert.deepEqual(preview, { available: true, text: '41 41 41', total_tokens: 256, offset: 4, next_offset: 7 });
assert.equal((await value('cache/text', { namespace: 'f'.repeat(64), block: '1'.repeat(64) })).reason, 'cache_not_found');
const busy = await call('cache/purge', { scope: 'namespace', namespace: 'c'.repeat(64), confirmed: true });
assert.equal(busy.error.code, 'tyloinfer/core-rejected');
assert.equal(busy.error.details.http_status, 409);
assert.equal(busy.error.details.core_error.code, 'runtime_busy');
assert.equal((await inventory()).total_blocks, 4);
const clear = await value('cache/clear', { instance_id: instanceId, confirmed: true });
assert.equal(clear.released_snapshots, 2);
assert.equal(clear.image_decode_cache_released_bytes, 7);
const trim = await value('cache/trim', { instance_id: instanceId, target_bytes: 0, confirmed: true });
assert.equal(trim.target_bytes, 0);
assert.equal(trim.released_bytes, 8);
assert.equal((await inventory()).total_blocks, 4);
const selected = await value('cache/purge', { scope: 'namespace', namespace: 'a'.repeat(64), confirmed: true });
assert.equal(selected.removed_blocks, 1);
assert.equal(selected.failed_blocks, 0);
assert.equal((await inventory()).total_blocks, 3);
const partial = await value('cache/purge', { scope: 'namespace', namespace: 'b'.repeat(64), confirmed: true });
assert.equal(partial.removed_blocks, 1);
assert.equal(partial.failed_blocks, 1);
const afterPartial = await inventory();
assert.equal(afterPartial.total_blocks, 2);
const all = await value('cache/purge', { scope: 'all', confirmed: true });
assert.equal(all.removed_blocks, 2);
assert.equal((await inventory()).total_blocks, 0);
const directory = (await read('model_directories')).data[0];
const configured = await value('downloads/configure-directory', { request: { directory_id: directory.id }, confirmed: true });
assert.ok(configured.directory);
assert.equal(configured.directory, configured.actual_directory);
const enabled = await value('downloads/configure-directory', { request: { evict_prefix_cache: true }, confirmed: true });
assert.equal(enabled.actual_directory, configured.actual_directory);
assert.equal(enabled.evict_prefix_cache, true);
const reset = await value('downloads/configure-directory', { request: { directory_id: null }, confirmed: true });
assert.equal(reset.directory, null);
assert.equal(reset.evict_prefix_cache, true);
assert.equal((await value('downloads/configure-directory', { request: { evict_prefix_cache: false }, confirmed: true })).evict_prefix_cache, false);
const job = await value('jobs/get', { job_id: jobId });
assert.equal(job.kind, 'maintenance.fixture');
assert.equal(job.status, 'succeeded');
assert.deepEqual(job.payload, { fixture: true });
const history = await value('jobs/events', { job_id: jobId, after: 0, limit: 1000, tail: false });
assert.ok(history.data.length >= 4);
assert.ok(history.data.some(row => row.type === 'log' && row.data.fixture));
const latest = await value('jobs/events', { job_id: jobId, limit: 2, tail: true });
assert.deepEqual(latest.data.map(row => row.sequence), history.data.slice(-2).map(row => row.sequence));
const incremental = await value('jobs/events', { job_id: jobId, after: history.data[0].sequence, limit: 1000 });
assert.deepEqual(incremental.data.map(row => row.sequence), history.data.slice(1).map(row => row.sequence));
assert.equal((await call('jobs/cancel', { job_id: jobId, confirmed: true })).error.code, 'tyloinfer/bad-request');
console.log('CORE_MAINTENANCE_BRIDGE_API_PASS; CACHE=isolated-fixtures; NATIVE_AND_TOKENIZER=controlled; DOWNLOADS=none');
