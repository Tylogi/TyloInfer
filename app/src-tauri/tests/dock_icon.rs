use icns::{IconFamily, IconType, PixelFormat};

#[test]
fn dock_icon_has_padding_and_the_tylogi_mark() {
    let family = IconFamily::read(&include_bytes!("../icons/icon.icns")[..])
        .expect("could not decode the ICNS generated by build.rs");
    let image = family
        .get_icon_with_type(IconType::RGBA32_256x256)
        .expect("Dock icon has no 256×256 frame")
        .convert_to(PixelFormat::RGBA);
    let pixel = |x: usize, y: usize| {
        let start = (y * image.width() as usize + x) * 4;
        &image.data()[start..start + 4]
    };

    for (x, y) in [(16, 128), (239, 128), (128, 16), (128, 239)] {
        assert_eq!(pixel(x, y)[3], 0, "missing Dock padding at ({x}, {y})");
    }
    assert_eq!(pixel(36, 128)[3], 255, "Dock padding is too wide");
    for (label, x, y) in [("crossbar", 85, 88), ("stem", 125, 145), ("foot", 165, 188)] {
        assert_eq!(pixel(x, y), [243, 241, 236, 255], "missing TL {label}");
    }
    assert_eq!(
        pixel(85, 145),
        [17, 19, 19, 255],
        "mark fills its negative space"
    );
    assert_eq!(pixel(186, 188), [185, 133, 76, 255], "missing accent dot");
}
